#!/usr/bin/env python3
"""Teilt die Testliste der VICE Testbench in N etwa gleich teure Teile auf.

Aufruf: split_testlist.py <testliste> <anzahl> <ausgabeverzeichnis> [gruppe ...]

- Alle Tests mit demselben Pfad (gleiches Verzeichnis) kommen in denselben Teil. Tests im selben
  Verzeichnis dürfen nicht parallel laufen, weil sie sich Disk Images und Screenshot Ordner teilen.
- Kosten eines Tests = sein Zyklenlimit (Spalte 4) plus ein fester Aufschlag für den Programmstart.
- Mit "gruppe" werden nur Tests genommen, deren Pfad die Zeichenkette enthält (z.B. "drive/scanner").
- Schreibt chunk-1.txt ... chunk-N.txt und gibt je Teil eine Zeile "Teil Tests Kosten" aus.
"""
import os
import sys

STARTUP_COST = 3_000_000


def main():
    if len(sys.argv) < 4:
        print(__doc__)
        return 2

    testlist, count, outdir = sys.argv[1], int(sys.argv[2]), sys.argv[3]
    groups = sys.argv[4:]

    by_path = {}
    order = []
    with open(testlist, encoding="utf-8") as f:
        for line in f:
            line = line.rstrip("\n")
            if not line.strip() or line.startswith("#"):
                continue
            fields = line.split(",")
            if len(fields) < 4:
                print("Fehler: Zeile mit zu wenigen Feldern: " + line, file=sys.stderr)
                return 1
            path = fields[0]
            if groups and not any(g in path for g in groups):
                continue
            try:
                cost = int(fields[3])
            except ValueError:
                cost = 0
            if path not in by_path:
                by_path[path] = []
                order.append(path)
            by_path[path].append((line, cost + STARTUP_COST))

    if not by_path:
        print("Fehler: Keine Tests gefunden (Filter: %s)" % " ".join(groups), file=sys.stderr)
        return 1

    count = max(1, min(count, len(by_path)))
    bins = [{"lines": [], "cost": 0} for _ in range(count)]

    # Teuerste Verzeichnisse zuerst, immer in den bisher leersten Teil (LPT Verfahren)
    paths = sorted(order, key=lambda p: -sum(c for _, c in by_path[p]))
    for path in paths:
        target = min(bins, key=lambda b: b["cost"])
        for line, cost in by_path[path]:
            target["lines"].append(line)
            target["cost"] += cost

    os.makedirs(outdir, exist_ok=True)
    for i, b in enumerate(bins, 1):
        with open(os.path.join(outdir, "chunk-%d.txt" % i), "w", encoding="utf-8") as f:
            f.write("# generated by split_testlist.py, do not edit.\n")
            for line in b["lines"]:
                f.write(line + "\n")
        print("%d %d %d" % (i, len(b["lines"]), b["cost"]))
    return 0


if __name__ == "__main__":
    sys.exit(main())
